/**
 * Project standards: the zod schema, the loader and the markdown renderer.
 * standards/*.json is the source; docs/standards.md is generated from it (bun run standards:gen).
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';

const enforcementSchema = z.discriminatedUnion('kind', [
  z.strictObject({ kind: z.literal('script'), check: z.string().min(1) }), // a package.json script name
  z.strictObject({ kind: z.literal('agent'), owner: z.string().min(1) }), // a skill or agent name
  z.strictObject({ kind: z.literal('human') }),
]);

const ruleSchema = z.strictObject({
  rule: z.string().min(1),
  why: z.string().min(1),
  enforcement: enforcementSchema,
});

/** Rule ids look like `core.typescript-only`; the prefix says which file may own the rule. */
const rulesFor = (prefixes: string[]) =>
  z.record(
    z
      .string()
      .regex(
        new RegExp(`^(${prefixes.join('|')})\\.[a-z0-9]+(-[a-z0-9]+)*$`),
        `rule id must be <${prefixes.join('|')}>.<kebab-name>`,
      ),
    ruleSchema,
  );

const FILES = {
  core: z.strictObject({
    goals: z.array(z.string().min(1)).min(1),
    nonGoals: z.array(z.string().min(1)).min(1),
    rules: rulesFor(['core', 'intake', 'backport', 'auth', 'release']),
  }),
  design: z.strictObject({ rules: rulesFor(['design']) }),
  variant: z.strictObject({
    variant: z.enum(['base', 'supabase', 'firebase']),
    rules: rulesFor(['supabase', 'firebase']),
  }),
};

export const standardsSchema = z.strictObject(FILES);
export type Standards = z.infer<typeof standardsSchema>;
type Enforcement = z.infer<typeof enforcementSchema>;

/** Reads standards/{core,design,variant}.json under root; throws `standards/<file>.json: <problem>`. */
export function loadStandards(root: string = process.cwd()): Standards {
  const out: Record<string, unknown> = {};
  for (const [name, schema] of Object.entries(FILES)) {
    const file = `standards/${name}.json`;
    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(join(root, file), 'utf8'));
    } catch (e) {
      throw new Error(`${file}: ${(e as Error).message}`);
    }
    const parsed = schema.safeParse(raw);
    if (!parsed.success) throw new Error(`${file}: ${z.prettifyError(parsed.error)}`);
    out[name] = parsed.data;
  }
  return standardsSchema.parse(out);
}

const enforcedBy = (e: Enforcement) =>
  e.kind === 'script' ? `script: ${e.check}` : e.kind === 'agent' ? `agent: ${e.owner}` : 'human';

/** Deterministic markdown: rules sorted by id, no timestamps. */
export function renderStandards(s: Standards): string {
  const rules = { ...s.core.rules, ...s.design.rules, ...s.variant.rules };
  const ids = Object.keys(rules).sort();
  const count = (r: object) => Object.keys(r).length;
  const out = [
    '<!-- Generated by `bun run standards:gen` from standards/*.json. Do not edit by hand. -->',
    '',
    '# Standards',
    '',
    `Variant: ${s.variant.variant} · Rules: ${ids.length} (core ${count(s.core.rules)}, design ${count(s.design.rules)}, variant ${count(s.variant.rules)})`,
    '',
    'Cite a rule as `path:line [rule.id]`.',
    '',
    '## Goals',
    '',
    ...s.core.goals.map((g) => `- ${g}`),
    '',
    '## Non-goals',
    '',
    ...s.core.nonGoals.map((g) => `- ${g}`),
    '',
    '## Rules',
  ];
  for (const id of ids) {
    const r = rules[id]!;
    out.push(
      '',
      `### ${id}`,
      '',
      r.rule,
      '',
      `- Why: ${r.why}`,
      `- Enforced by: ${enforcedBy(r.enforcement)}`,
    );
  }
  return out.join('\n') + '\n';
}
